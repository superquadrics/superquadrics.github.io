#!/bin/sh
# Packs the gripper meshes of each folder (OBJ and MTL as text, STL and the MTL textures as base64) into <folder>/<folder>.js,
# a classic script that index.html loads on demand with <script src>. Unlike fetch(), this also works
# when the page is opened from disk (file://). Rerun after changing the meshes:
#   sh assets/grippers/build_gripper_js.sh
set -e
cd "$(dirname "$0")"

for dir in franka_hand robotiq_2f85 umi_gripper; do
  {
    echo "// Generated by build_gripper_js.sh from the meshes in this folder; do not edit."
    echo "window.GRIPPER_FILES = window.GRIPPER_FILES || {};"
    for f in "$dir"/*.obj "$dir"/*.mtl; do
      [ -e "$f" ] || continue
      printf "window.GRIPPER_FILES['%s'] = \`" "$f"
      tr -d '\r' < "$f"
      echo "\`;"
    done
    for f in "$dir"/*.stl; do
      [ -e "$f" ] || continue
      printf "window.GRIPPER_FILES['%s'] = '%s';\n" "$f" "$(base64 -w 0 "$f")"
    done
    # textures of the MTL materials (map_Kd)
    for t in $(cat "$dir"/*.mtl 2>/dev/null | tr -d '\r' | awk '$1 == "map_Kd" { print $NF }' | sort -u); do
      printf "window.GRIPPER_FILES['%s/%s'] = '%s';\n" "$dir" "$t" "$(base64 -w 0 "$dir/$t")"
    done
  } > "$dir/$dir.js"
done
